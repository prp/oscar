//! The launch's configuration as one typed value, parsed once; nothing writes the environment.

use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::OnceLock;

use super::{BudgetSource, KvCharge};
use oscar_models::rows::ModelPreset;

/// Every `OSCAR_*` config parameter oscar or a fork reads; any other stops the launch, as a typo would run a default.
const KNOWN_OSCAR_ENV: &[&str] = &[
    "OSCAR_MEM_TOTAL_GB",
    "OSCAR_PLAN_KV",
    "OSCAR_KV_CACHE_DISK_GB",
    "OSCAR_MODELS_DIR",
    "OSCAR_PAGED_BLOCK",
    "OSCAR_APPROX_ROUTING",
    "OSCAR_DRAFT_APPROX_ROUTING",
    "OSCAR_MEM_WATCHDOG_GB",
    "OSCAR_IO_THREADS",
    "OSCAR_ORACLE",
    "OSCAR_LOOKAHEAD",
    "OSCAR_PREFETCH_CHANNELS",
    "OSCAR_DRAFT",
    "OSCAR_DRAFT_K",
    "OSCAR_DRAFT_STAGE_LEAD_TOKENS",
    "OSCAR_EVICTION_CHANNELS",
    "OSCAR_LOOKAHEAD_STAGE_MAX_EXPERTS",
    "OSCAR_LOOKAHEAD_STAGE_MARGIN",
    "OSCAR_PREFILL_CHUNK",
    "OSCAR_GPU_HEARTBEAT_US",
    "OSCAR_DBG_DIAG",
];

/// Harness-input prefixes (bench and eval configuration).
const KNOWN_OSCAR_PREFIXES: &[&str] = &["OSCAR_BENCH_", "OSCAR_MMLU_", "OSCAR_GEN_", "OSCAR_TEST_"];

pub fn reject_unknown_oscar_env() {
    let mut unknown: Vec<String> = std::env::vars()
        .map(|(k, _)| k)
        .filter(|k| k.starts_with("OSCAR_"))
        .filter(|k| !KNOWN_OSCAR_ENV.contains(&k.as_str()))
        .filter(|k| !KNOWN_OSCAR_PREFIXES.iter().any(|p| k.starts_with(p)))
        .collect();
    if !unknown.is_empty() {
        unknown.sort();
        panic!(
            "unknown OSCAR_* env var(s): {} - launch stops; registry KNOWN_OSCAR_ENV in \
             oscar-runtime/src/config/params.rs",
            unknown.join(", ")
        );
    }
}

/// The launch's configuration, parsed once.
pub struct Params {
    /// The told budget, the ceiling a plan is sized under.
    pub budget_gb: f64,
    pub source: BudgetSource,
    pub charge: KvCharge,
    /// The drafter armed: its reserve, hints, staging plane and eviction leg follow this, with no switch of their own.
    pub draft: bool,
    /// The depth drafted ahead each round.
    pub draft_k: usize,
    /// Zero is off.
    pub heartbeat_us: u64,
    /// The KV block size in tokens, a layout tunable: generated bytes must not move with it.
    pub paged_block: u64,
    /// The legs eviction reads; a replay turns the lookahead's staging off, not its leg.
    pub eviction: EvictionChannels,
    pub ep: EventLaneParams,
    /// `transition`, `recency` (its reuse-distance prior, for flat routing) or `lru`; unset under a replay is Belady.
    pub oracle: String,
    pub misc: MiscKnobs,
    /// A cold selection weighing under θ becomes the best resident expert, changing the model; softmax routers only.
    pub approx_theta: Option<f32>,
    /// The draft forward takes resident experts for cold ones; the engine's tokens stay exact, only the drafts move.
    pub draft_approx_routing: bool,
}

/// One lookahead or none, named for where the router product is computed: a second adds nothing for its cost.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lookahead {
    None,
    /// The next layer's routing, blitted from the GPU for the resolver: every architecture runs it, no host tables.
    Gpu,
    /// Layers further ahead on the resolver thread: more horizon, paid in host matvecs and router-table memory.
    Host,
}

/// A config parameter's value by name: the one source every parse reads.
type Get<'a> = &'a dyn Fn(&str) -> Option<String>;

/// Unset or empty is `default`; a value that does not parse stops the launch, as a typo would run the default.
fn number<T: std::str::FromStr>(get: Get, key: &str, default: T) -> T {
    match get(key).filter(|v| !v.is_empty()) {
        None => default,
        Some(v) => v.parse().unwrap_or_else(|_| panic!("{key}={v:?}: expected number")),
    }
}

/// `1`/`true` on, `0`/`false` off, unset or empty `default`; any other value stops the launch.
fn switch(get: Get, key: &str, default: bool) -> bool {
    match get(key).as_deref() {
        None | Some("") => default,
        Some("1" | "true") => true,
        Some("0" | "false") => false,
        Some(v) => panic!("{key}={v:?}: expected 1 or 0"),
    }
}

/// Unset is [`Lookahead::Gpu`], a new architecture's starting point, as every model's row names its own.
fn lookahead(get: Get) -> Lookahead {
    match get("OSCAR_LOOKAHEAD").as_deref() {
        None | Some("") | Some("gpu") => Lookahead::Gpu,
        Some("none") => Lookahead::None,
        Some("host") => Lookahead::Host,
        Some(v) => panic!(
            "OSCAR_LOOKAHEAD={v:?}: expected none | gpu | host (where router product runs); one mechanism, not a set"
        ),
    }
}

fn draft(get: Get) -> bool {
    match get("OSCAR_DRAFT").as_deref() {
        Some("self") => true,
        None | Some("") | Some("none") => false,
        Some(other) => panic!("OSCAR_DRAFT={other:?}: expected self | none (depth: OSCAR_DRAFT_K)"),
    }
}

/// A staging plane's bit in [`EventLaneParams::staging_planes`].
pub const PLANE_GPU: u8 = 1 << 0;
pub const PLANE_DRAFT: u8 = 1 << 1;
pub const PLANE_HOST: u8 = 1 << 2;

/// The transition oracle's legs, so a source that degrades eviction stays out of it.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct EvictionChannels {
    pub lookahead: bool,
    pub draft: bool,
    pub rollout: bool,
}

/// `key`'s comma list of families, each `(name, armed)`: unset is every armed one, `none` none; an unknown name or an
/// unarmed family stops the launch. Returns which are named.
fn family_list<const N: usize>(get: Get, key: &str, families: [(&str, bool); N]) -> [bool; N] {
    let Some(spec) = get(key).filter(|s| !s.is_empty()) else { return families.map(|(_, armed)| armed) };
    let mut named = [false; N];
    for tok in spec.split(',').map(str::trim).filter(|t| *t != "none") {
        let Some(i) = families.iter().position(|(name, _)| *name == tok) else {
            panic!("{key} token {tok:?}: expected {} | none, listed", families.map(|f| f.0).join(" | "));
        };
        assert!(families[i].1, "{key} names `{tok}`, but no {tok} mechanism is armed to produce claims");
        named[i] = true;
    }
    named
}

/// `OSCAR_EVICTION_CHANNELS`: the families whose claims eviction reads; unset, every armed one and the rollout.
fn eviction_channels(get: Get, lookahead_armed: bool, draft_armed: bool) -> EvictionChannels {
    let families = [("lookahead", lookahead_armed), ("draft", draft_armed), ("rollout", true)];
    let [lookahead, draft, rollout] = family_list(get, "OSCAR_EVICTION_CHANNELS", families);
    EvictionChannels { lookahead, draft, rollout }
}

/// The armed planes `OSCAR_PREFETCH_CHANNELS` lets prefetch, a `PLANE_*` bit each; eviction is gated apart.
fn staging_planes(get: Get, draft_armed: bool, lookahead: Lookahead, eviction: EvictionChannels) -> u8 {
    let planes = match lookahead {
        Lookahead::None => 0,
        Lookahead::Gpu => PLANE_GPU,
        Lookahead::Host => PLANE_HOST,
    };
    let [pf_draft, pf_look] =
        family_list(get, "OSCAR_PREFETCH_CHANNELS", [("draft", draft_armed), ("lookahead", planes != 0)]);
    // An armed mechanism nothing consumes runs for nothing.
    for (armed, name, consumed) in [
        (draft_armed, "OSCAR_DRAFT", pf_draft || eviction.draft),
        (planes != 0, "OSCAR_LOOKAHEAD", pf_look || eviction.lookahead),
    ] {
        assert!(
            !armed || consumed,
            "{name} arms a mechanism neither OSCAR_PREFETCH_CHANNELS nor OSCAR_EVICTION_CHANNELS consumes: its \
             predictions would be made and discarded; name a consumer, or turn it off with {name}=none"
        );
    }
    (if pf_draft { PLANE_DRAFT } else { 0 }) | (if pf_look { planes } else { 0 })
}

/// The event lane protocol's config parameters (`crate::engine::event_lane`).
pub struct EventLaneParams {
    /// A bit per plane, gating staging IO only: a masked plane still feeds eviction, so any mask is byte-exact.
    pub staging_planes: u8,
    /// Caps the admitted candidates a chain-eval target stages (0: no cap), as an uncapped flood congests demand reads.
    pub lookahead_stage_max_experts: usize,
    /// Admits a candidate only where its score clears the predicted rank-cut by this, in router score units; 0 off.
    pub lookahead_stage_margin: f32,
    /// None under a replay, whatever `OSCAR_LOOKAHEAD` names.
    pub lookahead: Lookahead,
    /// Four, unset, hides a perfect predictor's cold reads; deeper stages only what a wrong prediction will not need.
    pub draft_stage_lead_tokens: usize,
}

pub struct MiscKnobs {
    /// Gates the periodic mid-generation lines, not banners or errors; a front end's default is off below `-vv`.
    pub diag: bool,
    pub io_threads: usize,
    /// The context store's disk budget.
    pub kv_cache_disk_gb: u64,
    /// The eval's prefill width over the recorded one, with its region in bytes where given.
    pub prefill_chunk: Option<(usize, Option<usize>)>,
    /// The OS-headroom floor in GB, 0 off; the default sits between a load's lowest headroom and the death state.
    pub mem_watchdog_gb: f64,
}

impl Params {
    /// A user's exports over the model's row ([`super::launch_params`]); `xy` charged, else the bench's sequence.
    pub fn for_launch(
        preset: ModelPreset, budget: (f64, BudgetSource), xy: Option<(u64, u64, bool)>, verbose: Option<u8>,
    ) -> Self {
        let rows = super::launch_params(preset, (budget.0 * crate::machine::GB) as u64);
        let get = |k: &str| {
            let row = rows.iter().find(|r| r.key == k);
            match row.filter(|r| r.forced) {
                Some(r) => Some(r.value.clone()),
                None => std::env::var(k).ok().or_else(|| row.map(|r| r.value.clone())),
            }
        };
        let diag = |k: &str| match k {
            "OSCAR_DBG_DIAG" => get(k).or_else(|| verbose.map(|v| if v >= 2 { "1" } else { "0" }.to_string())),
            _ => get(k),
        };
        Self::parse(&diag, budget, xy)
    }

    /// A bench's launch: its environment alone, print-config's stdout among it.
    pub fn from_env() -> Self {
        let get = |k: &str| std::env::var(k).ok();
        let budget = super::told_budget_gb(None).unwrap_or_else(|e| panic!("{e}"));
        // A window from the environment is asked, as one from the command line is.
        let xy = super::plan_kv_from(get("OSCAR_PLAN_KV")).map(|(x, y)| (x, y, true));
        Self::parse(&get, budget, xy)
    }

    fn parse(get: Get, budget: (f64, BudgetSource), xy: Option<(u64, u64, bool)>) -> Self {
        let replay_mode = REPLAY.load(Ordering::Relaxed);
        if replay_mode {
            tracing::info!(target: "oscar::eval", "trace replay - lookahead off (trace is prediction)");
        }
        let draft = draft(get);
        let lookahead = lookahead(get);
        let eviction = eviction_channels(get, lookahead != Lookahead::None, draft);
        let staging = staging_planes(get, draft, lookahead, eviction);
        Self {
            budget_gb: budget.0,
            source: budget.1,
            charge: super::KvCharge::of_launch(xy, draft),
            draft,
            draft_k: match number(get, "OSCAR_DRAFT_K", 16usize) {
                0 => panic!("OSCAR_DRAFT_K=0: K is round depth, not off switch; drafter off with OSCAR_DRAFT=none"),
                k => k,
            },
            heartbeat_us: number(get, "OSCAR_GPU_HEARTBEAT_US", 0),
            paged_block: match number(get, "OSCAR_PAGED_BLOCK", 32u64) {
                b @ (8 | 16 | 32) => b,
                b => panic!("OSCAR_PAGED_BLOCK={b} must be 8, 16 or 32"),
            },
            eviction,
            ep: EventLaneParams {
                staging_planes: staging,
                // The trace knows every token's experts, so a lookahead beside a replay stages nothing yet costs time.
                lookahead_stage_max_experts: number(get, "OSCAR_LOOKAHEAD_STAGE_MAX_EXPERTS", 0)
                    * usize::from(!replay_mode),
                lookahead_stage_margin: number(get, "OSCAR_LOOKAHEAD_STAGE_MARGIN", 0.0),
                lookahead: if replay_mode { Lookahead::None } else { lookahead },
                draft_stage_lead_tokens: match number(get, "OSCAR_DRAFT_STAGE_LEAD_TOKENS", 4) {
                    0 => panic!("OSCAR_DRAFT_STAGE_LEAD_TOKENS=0: expected at least one token"),
                    n => n,
                },
            },
            oracle: get("OSCAR_ORACLE").unwrap_or_default(),
            approx_theta: match get("OSCAR_APPROX_ROUTING").as_deref() {
                None | Some("") | Some("0") | Some("0.0") => None,
                // Every cold selection substitutes (θ ≥ 1): a performance ceiling to compare against, never a user's.
                Some("resident") => Some(2.0),
                Some(v) => {
                    let theta: f32 = v.parse().unwrap_or_else(|e| {
                        panic!("OSCAR_APPROX_ROUTING={v}: expected theta in (0, 1) or `resident` ({e})")
                    });
                    if !(theta > 0.0 && theta < 1.0) {
                        panic!("OSCAR_APPROX_ROUTING={v}: theta must be in (0, 1) (or `resident`)");
                    }
                    if replay_mode {
                        // A replay is a byte-exact ceiling; an approximate number would poison its tables.
                        panic!(
                            "OSCAR_APPROX_ROUTING refused under replay - approximate output never enters byte-exact \
                             tables"
                        );
                    }
                    tracing::info!(target: "oscar::eval",
                        "approximate routing armed (theta = {theta}) - cold selections below theta replaced by \
                         resident experts; output not byte-exact"
                    );
                    Some(theta)
                }
            },
            draft_approx_routing: switch(get, "OSCAR_DRAFT_APPROX_ROUTING", false),
            misc: MiscKnobs {
                diag: switch(get, "OSCAR_DBG_DIAG", true),
                io_threads: number(get, "OSCAR_IO_THREADS", 8),
                kv_cache_disk_gb: number(get, "OSCAR_KV_CACHE_DISK_GB", 256),
                prefill_chunk: get("OSCAR_PREFILL_CHUNK").filter(|v| !v.is_empty()).map(|v| {
                    let mut f = v.split(':').map(|n| n.parse::<usize>().ok());
                    match (f.next().flatten(), f.next(), f.next()) {
                        (Some(t), None, None) if t > 0 => (t, None),
                        (Some(t), Some(Some(mib)), None) if t > 0 => (t, Some(mib << 20)),
                        _ => panic!("OSCAR_PREFILL_CHUNK={v:?}: expected <tokens>[:<region MB>], tokens above 0"),
                    }
                }),
                mem_watchdog_gb: match number(get, "OSCAR_MEM_WATCHDOG_GB", super::DEFAULT_WATCHDOG_FLOOR_GB) {
                    g if g >= 0.0 => g,
                    g => panic!("OSCAR_MEM_WATCHDOG_GB={g}: expected GB (0 = watchdog off, unset = 1.5)"),
                },
            },
        }
    }
}

static REPLAY: AtomicBool = AtomicBool::new(false);

/// The eval's, at its install: under a replay the lookahead stands down and approximation is refused.
pub fn set_replay(on: bool) {
    REPLAY.store(on, Ordering::Relaxed);
}

static KNOBS: OnceLock<Params> = OnceLock::new();

/// The front end's configuration, else the bench's environment parsed at the first ask.
pub fn params() -> &'static Params {
    KNOBS.get_or_init(|| {
        let k = Params::from_env();
        oscar_models::draft::set_self_draft(k.draft);
        k
    })
}

/// A front end's launch, set once before anything reads a config parameter.
pub fn configure(params: Params) {
    oscar_models::draft::set_self_draft(params.draft);
    assert!(KNOBS.set(params).is_ok(), "the launch's configuration is set once, before anything reads it");
}

/// The host line books router tables by it; never under test, where a test's environment is not a launch's.
pub fn lookahead_is_host() -> bool {
    !cfg!(test) && params().ep.lookahead == Lookahead::Host
}

/// What the host line counts bounce buffers by: eight under test, as unset.
pub fn io_threads() -> usize {
    if cfg!(test) {
        8
    } else {
        params().misc.io_threads
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lookahead_names_one_mechanism() {
        let (draft, gpu, host) = (PLANE_DRAFT, PLANE_GPU, PLANE_HOST);
        let with = |v: Option<&str>| {
            let get = |k: &str| v.filter(|_| k == "OSCAR_LOOKAHEAD").map(str::to_string);
            let la = lookahead(&get);
            staging_planes(&get, true, la, eviction_channels(&get, la != Lookahead::None, true))
        };
        // Unset starts a new architecture on the plane that asks least of it.
        assert_eq!(with(None), draft | gpu);
        assert_eq!(with(Some("none")) & (gpu | host), 0);
        assert_eq!(with(Some("gpu")) & (gpu | host), gpu);
        assert_eq!(with(Some("host")) & (gpu | host), host);
        assert_eq!(with(Some("gpu")) & draft, draft);
        // Alternatives, so a set is a refusal rather than a union.
        for bad in ["d1", "chain", "md", "gpu,host", "delta1", "all"] {
            assert!(std::panic::catch_unwind(|| with(Some(bad))).is_err(), "OSCAR_LOOKAHEAD={bad} should refuse");
        }
    }
}
